function DesignIcon({
  name,
  size = 24,
  color,
  accessible = false,
  accessibilityElementsHidden = true,
  importantForAccessibility = "no-hide-descendants",
}: Omit<ComponentProps<typeof NativeIonicons>, "name"> & {
  readonly name: keyof typeof DESIGN_ICON_MAP;
}) {
  const palette = usePalette();
  const Glyph = DESIGN_ICON_MAP[name];
  if (!Glyph) throw new Error(`Missing Figma icon mapping: ${name}`);
  return (
    <Glyph
      size={size}
      color={typeof color === "string" ? color : palette.text}
      strokeWidth={2}
      accessible={accessible}
      accessibilityElementsHidden={accessibilityElementsHidden}
      importantForAccessibility={importantForAccessibility}
    />
  );
}

export default Object.assign(DesignIcon, { glyphMap: DESIGN_ICON_MAP });
