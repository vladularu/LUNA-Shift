import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const GENERATED_PATH = "src/features/analysis/analysis-cache-version.generated.ts";
const roots = [
  "src/domain",
  "src/engine",
  "src/rules",
  "src/features/salary",
  "src/features/analysis",
];
const dependencies = ["@js-temporal/polyfill", "jsbi", "bigdecimal.js", "canonicalize", "ajv"];
const hash = (value) => createHash("sha256").update(value).digest("hex");

/** Include calculation/validation code, not screens, hook orchestration or test fixtures. */
export function isCalculationSource(file) {
  if (file === GENERATED_PATH || /(?:\.test\.|test-fixtures\.|test-data-generator\.)/.test(file))
    return false;
  if (!/\.(?:tsx?|json)$/.test(file)) return false;
  if (["src/domain/", "src/engine/", "src/rules/"].some((root) => file.startsWith(root)))
    return true;
  return (
    /^src\/features\/(?:salary|analysis)\//.test(file) &&
    file.endsWith(".ts") &&
    !path.posix.basename(file).startsWith("use-")
  );
}

export function calculationContract(root) {
  const files = [];
  function visit(relative) {
    const directory = path.join(root, relative);
    if (!existsSync(directory)) return;
    for (const item of readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
      a.name.localeCompare(b.name, "en"),
    )) {
      const file = relative + "/" + item.name;
      if (item.isSymbolicLink()) throw new Error("Calculation source cannot be a symlink: " + file);
      if (item.isDirectory()) visit(file);
      else if (isCalculationSource(file))
        files.push({
          path: file,
          sha256: hash(readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n")),
        });
    }
  }
  roots.forEach(visit);
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  if (files.length === 0) throw new Error("No calculation sources found");
  const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
  const lock = JSON.parse(readFileSync(path.join(root, "package-lock.json"), "utf8"));
  const versions = dependencies.map((name) => [
    name,
    lock.packages?.["node_modules/" + name]?.version ?? pkg.dependencies?.[name] ?? null,
  ]);
  const digest = hash(JSON.stringify({ format: 3, files, dependencies: versions }));
  return { version: "luna-analysis-v3:" + digest, files, dependencies: versions };
}

export function renderContract(contract) {
  return (
    "// Generated by node scripts/analysis-cache-contract.mjs --write; checked by verify:fast.\n" +
    "// Change calculation sources to invalidate results; UI-only updates keep this identity.\n" +
    "export const ANALYSIS_RESULT_CALCULATION_VERSION =\n  " +
    JSON.stringify(contract.version) +
    ";\n"
  );
}

export function verifyContract(root) {
  const contract = calculationContract(root),
    expected = renderContract(contract);
  const target = path.join(root, GENERATED_PATH);
  if (!existsSync(target) || readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== expected)
    throw new Error(
      "Analysis calculation contract is stale. Run node scripts/analysis-cache-contract.mjs --write and review the resulting cache invalidation.",
    );
  return contract;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  try {
    const contract = calculationContract(root);
    if (process.argv.includes("--write"))
      writeFileSync(path.join(root, GENERATED_PATH), renderContract(contract));
    else verifyContract(root);
    console.log(
      JSON.stringify({
        version: contract.version,
        sourceFiles: contract.files.length,
        checked: !process.argv.includes("--write"),
      }),
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
