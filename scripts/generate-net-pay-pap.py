"""Reproduce the offline PAP module from the pinned official XML and LstGen commit."""

import argparse
import gzip
import hashlib
import io
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
GENERATOR_COMMIT = "2e6342e3a33857fa0ee9d0d255c978c717c0df61"
XML_SHA256 = "63d8981646d139eba2f4dd990c13b43c4fb3883b402a5a40cddf253aa7aa96b4"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--lstgen-source", required=True, type=Path)
parser.add_argument("--python-dependencies", type=Path)
args = parser.parse_args()
source = args.lstgen_source.resolve()
commit = subprocess.check_output(
    ["git", "-C", str(source.parent), "rev-parse", "HEAD"], text=True
).strip()
if commit != GENERATOR_COMMIT:
    raise SystemExit("LstGen source does not match the reviewed generator commit")
sys.path.insert(0, str(source))
if args.python_dependencies:
    sys.path.insert(1, str(args.python_dependencies.resolve()))

from lxml import etree  # noqa: E402
from lstgen import PapParser  # noqa: E402
from lstgen.generators import GENERATORS  # noqa: E402

xml = gzip.decompress((ROOT / "scripts/fixtures/net-pay/Lohnsteuer2026.xml.gz").read_bytes())
if hashlib.sha256(xml).hexdigest() != XML_SHA256:
    raise SystemExit("Official PAP XML checksum mismatch; review the new rules first")
output = ROOT / "src/vendor/bmf/lohnsteuer2026.ts"
generated = io.StringIO()
GENERATORS["typescript"](
    PapParser(etree.fromstring(xml)), generated, class_name="Lohnsteuer2026", indent="  "
).generate()
with output.open("w", encoding="utf-8", newline="\n") as target:
    target.write(
        "// Generated by scripts/generate-net-pay-pap.py; do not edit by hand.\n"
        f"// BMF PAP 2026 XML SHA-256: {XML_SHA256}\n"
        f"// LstGen commit: {GENERATOR_COMMIT}; license: LICENSE-LstGen.txt\n"
    )
    # Syntax-only normalization to the repository's ESLint array convention.
    target.write(generated.getvalue().replace("ReadonlyArray<BigDecimal>", "readonly BigDecimal[]"))
print(f"Generated {output.relative_to(ROOT)}; run Prettier on this file afterwards.")
